namespace Cratis.CritterStack.Screenplay.given;

/// <summary>
/// Builds analysis contexts over minimal Marten, Wolverine and Wolverine-Marten API stubs for atomic admission specs.
/// </summary>
public class an_atomic_adapter_probe_context : Specification
{
    protected const string WolverineUse =
        """
        namespace App;
        public static class Sender
        {
            public static System.Threading.Tasks.Task Send(Wolverine.IMessageBus bus) => bus.SendAsync(new object());
        }
        """;

    protected const string WolverineAttributeUse =
        """
        namespace App;
        public static class Endpoints
        {
            [Wolverine.Http.WolverineGet("/things")]
            public static int Get() => 1;
        }
        """;

    protected const string MartenUse =
        """
        namespace App;
        public static class Saver
        {
            public static void Save(Marten.IDocumentSession session) => session.Store(new object());
        }
        """;

    protected const string IntegrationUse =
        """
        namespace App;
        public static class Ops
        {
            public static void Save() => Wolverine.Marten.MartenOps.Store(new object());
        }
        """;

    protected const string AllFamiliesUse =
        """
        namespace App;
        public static class Everything
        {
            public static System.Threading.Tasks.Task Run(Wolverine.IMessageBus bus, Marten.IDocumentSession session)
            {
                session.Store(new object());
                Wolverine.Marten.MartenOps.Store(new object());
                return bus.SendAsync(new object());
            }
        }
        """;

    protected const string NoUse = "namespace App; public sealed class Nothing;";

    const string FrameworkSource =
        """
        namespace Marten
        {
            public interface IDocumentSession { void Store<T>(T document); }
        }
        namespace Wolverine
        {
            public interface IMessageBus { System.Threading.Tasks.Task SendAsync(object message); }
        }
        namespace Wolverine.Http
        {
            public class WolverineGetAttribute(string route) : System.Attribute;
        }
        namespace Wolverine.Marten
        {
            public static class MartenOps { public static void Store<T>(T document) { } }
        }
        """;

    static readonly IReadOnlyList<MetadataReference> _references =
    [
        .. ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES"))
            .Split(Path.PathSeparator)
            .Select(path => MetadataReference.CreateFromFile(path))
    ];

    protected static DotNetAnalysisContext CreateContext(string applicationSource, bool stableSource = true, bool generatedApplication = false)
    {
        var framework = CSharpSyntaxTree.ParseText(FrameworkSource, path: "/checkout/App/Framework.cs");
        var application = CSharpSyntaxTree.ParseText(
            generatedApplication ? "// <auto-generated/>\n" + applicationSource : applicationSource,
            path: "/checkout/App/Application.cs");
        var compilation = CSharpCompilation.Create(
            "App",
            [framework, application],
            _references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));
        var sourceContext = stableSource
            ? DotNetSourcePaths.Create(
                "App/App",
                new DotNetSourcePathPolicy
                {
                    DisplayRoot = DotNetSourceDisplayRoot.Workspace,
                    CasePolicy = DotNetSourcePathCasePolicy.Ordinal
                },
                [
                    new DotNetSourceDocument { SyntaxTree = framework, ProjectRelativePath = "Framework.cs", WorkspaceRelativePath = "App/Framework.cs" },
                    new DotNetSourceDocument { SyntaxTree = application, ProjectRelativePath = "Application.cs", WorkspaceRelativePath = "App/Application.cs" }
                ])
            : null;
        return new DotNetAnalysisContext(
        [
            new DotNetProjectCompilation
            {
                Name = "App",
                Compilation = compilation,
                AuthoredSyntaxTrees = new HashSet<SyntaxTree> { framework, application },
                SourceContext = sourceContext,
                SourceRoot = stableSource ? null : "/checkout"
            }
        ]);
    }
}
